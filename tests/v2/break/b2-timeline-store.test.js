// Break round F103, b2-timeline: the state following the chat timeline (store.js, persist.js, turn.js,
// rewind.js). Each test failed on a1cf5b1. Since #76 wallet.receive is refused from a button, so the
// reader's action here is scene.present. B-4 (b2-timeline-checkpoints), B-5 and B-11
// (b2-timeline-capture) are in their own files.
import test from 'node:test';
import assert from 'node:assert/strict';
import { createHost } from '../../../testkit/index.js';
import { readRecord } from '../../../src/v2/persist.js';

const items = h => {
    const inv = h.head()?.domains?.inventory;
    return inv ? Object.values(inv.stacks).map(stack => inv.defs[stack.def]?.name).sort() : null;
};
const present = h => [...(h.head()?.domains?.scene?.present ?? [])];
const reply = (text, lines) => `${text}\n<Changes>\n${lines.join('\n')}\n</Changes>`;
async function host(t, options) {
    t.mock.method(console, 'warn', () => {});
    const h = await createHost(options);
    t.after(() => h.close());
    return h;
}

test('B-b2-timeline-3: deleting the greeting does not erase the next reply\'s stored changes', async t => {
    const h = await host(t);
    assert.equal((await h.sdk.command('scene.present', { add: 'Ann' })).ok, true);   // on the greeting
    await h.send('a', reply('A rope.', ['+ item Rope']));
    await h.send('b', reply('A lamp.', ['+ item Lamp']));
    const ropeRecord = structuredClone(readRecord(h.ctx.chat[2]));
    assert.equal(ropeRecord.receipts.length, 1);
    await h.st.deleteMessage(0);                    // the reader deletes the greeting
    const record = readRecord(h.ctx.chat[1]);       // the rope reply is now the first carrier
    assert.deepEqual(record?.receipts?.map(r => r.type), ['capture.item'], 'the rope reply keeps its receipt (actual: ensureInitial overwrote its record with an empty one)');
    assert.deepEqual(items(h), ['Lamp', 'Rope'], `the rope and the lamp stay (actual: ${items(h)})`);
    assert.deepEqual(present(h), ['Ann'], 'and what the greeting ended with is where the story now starts');
});

test('B-b2-timeline-6: a swipe holding a copied record does not inherit the deleted swipe\'s state', async t => {
    // SillyTavern copies `extra` into a new swipe. When that swipe was not captured by Story Block
    // (extension off, the interceptor failed, generated by another tool), it keeps swipe 0's record as
    // a copy (same sid, swipe: 0). readRecord ignores it only while swipe 0 still exists.
    const h = await host(t);
    await h.send('a', reply('A rope.', ['+ item Rope']));
    // SillyTavern dates every swipe (send_date): the reply as Story Block wrote its record.
    h.ctx.chat[2].send_date = h.ctx.chat[2].swipe_info[0].send_date = 'May 1, 2026 10:00am';
    assert.equal((await h.sdk.command('scene.present', { add: 'Bo' })).ok, true);
    await h.store.flush();
    const chat = structuredClone(h.ctx.chat);
    const m = chat[2];
    m.swipes.push('Nothing happens here.');
    m.swipe_info.push({ send_date: 'May 1, 2026 10:07am', extra: structuredClone(m.extra) });     // the copy
    m.swipe_id = 1;
    m.mes = m.swipes[1];
    m.send_date = m.swipe_info[1].send_date;
    await h.st.loadChat(chat);
    assert.deepEqual(items(h), [], 'precondition: swipe 1 has no state of its own');
    // The reader deletes swipe 0 (SillyTavern: splice swipes/swipe_info, show the neighbour).
    const msg = h.ctx.chat[2];
    msg.swipes.splice(0, 1);
    msg.swipe_info.splice(0, 1);
    msg.swipe_id = 0;
    msg.mes = msg.swipes[0];
    msg.send_date = msg.swipe_info[0].send_date;
    msg.extra = structuredClone(msg.swipe_info[0].extra);
    await h.st.eventSource.emit('message_swipe_deleted', { messageId: 2, swipeId: 0 });
    assert.deepEqual([items(h), present(h)], [[], []], `the remaining swipe still has nothing (actual: the deleted swipe's ${items(h)} and ${present(h)})`);
});

test('B-b2-timeline-7: a malformed checkpoint (no meta, no domains) is a Problem, not the state', async t => {
    const h = await host(t);
    await h.send('a', reply('A rope.', ['+ item Rope']));
    await h.store.flush();
    const chat = structuredClone(h.ctx.chat);
    chat[0].extra.storySuite.checkpoint = {};
    chat[0].swipe_info[0].extra.storySuite.checkpoint = {};
    await h.st.loadChat(chat);
    const result = await h.sdk.command('scene.present', { add: 'Cy' });
    assert.ok(!/Cannot read properties|is not a function|undefined/.test(result.message ?? ''), `no raw TypeError reaches the reader (actual: "${result.message}")`);
    assert.ok(h.store.problems().length > 0 || h.turn.problems().length > 0, 'the broken checkpoint is listed as a Problem (actual: none; head() is {})');
});

test('B-b2-timeline-8: a rewind that cannot take the changes back leaves the reader on the chat they were in', async t => {
    const h = await host(t);
    await h.send('a', reply('A rope.', ['+ item Rope']));
    await h.send('b', reply('Rope used, a lamp.', ['- item Rope', '+ item Lamp']));
    await h.st.deleteMessage(2);                       // the rope reply: the last reply no longer applies
    const index = h.ctx.chat.length - 1;
    const rev = readRecord(h.ctx.chat[index]).receipts.at(-1).rev;
    const before = h.ctx.chatId;
    const result = await h.sdk.rewind({ index, beforeRev: rev });
    assert.equal(result.ok, false);
    assert.equal(h.ctx.chatId, before, `no stray branch is opened when nothing was taken back (actual: now on "${h.ctx.chatId}")`);
});

test('B-b2-timeline-9: Continue on a reply whose stored `narrated` is malformed still keeps the reply\'s changes and saves', async t => {
    const h = await host(t);
    await h.send('a', 'The door opens');
    const chat = structuredClone(h.ctx.chat);
    chat[2].extra.storySuite.narrated = [null, 5];          // a partial / hand-edited record (still well-formed for readRecord)
    chat[2].swipe_info[0].extra.storySuite.narrated = [null, 5];
    await h.st.loadChat(chat);
    await h.cont(' and a lamp is there.\n<Changes>\n+ item Lamp\n</Changes>');
    const failed = h.turn.problems().filter(p => /could not be kept/.test(p.message));
    assert.deepEqual(failed.map(p => p.message), [], 'the turn completes (actual: "Narrated receipts must be a list of receipt IDs" aborts it before the save and the hiding)');
    assert.equal(h.store.dirty(), false, 'and the reply is saved');
});
